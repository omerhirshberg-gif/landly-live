"""Builds the "Landly" wordmark as one vector path and writes
lib/brand/wordmarkPath.ts.

The wordmark is Montserrat Bold (SIL Open Font License 1.1, which allows
embedding its outlines) at its default spacing and kerning -- matched against
the old 169x48 raster wordmark to within anti-aliasing. Its glyph outlines are
shaped with HarfBuzz (so kerning applies), flipped to SVG's y-down space and
framed by their own ink bounds, so centring the box centres the letters.

    python3 -m pip install fonttools uharfbuzz
    curl -LO 'https://github.com/google/fonts/raw/main/ofl/montserrat/Montserrat%5Bwght%5D.ttf'
    python3 scripts/generate-wordmark-path.py 'Montserrat[wght].ttf'
"""
import io
import sys
from pathlib import Path

import uharfbuzz as hb
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

TEXT = 'Landly'
WEIGHT = 700
# The old raster's ink (#000f3a at ~90% alpha) composited on white, the same
# ink the live slogan uses.
COLOR = '#19264b'
OUT = Path(__file__).resolve().parents[1] / 'lib/brand/wordmarkPath.ts'

font = TTFont(sys.argv[1])
if 'fvar' in font:
    font = instantiateVariableFont(font, {'wght': WEIGHT})
data = io.BytesIO()
font.save(data)
font = TTFont(io.BytesIO(data.getvalue()))
glyphs = font.getGlyphSet()
order = font.getGlyphOrder()

buf = hb.Buffer()
buf.add_str(TEXT)
buf.guess_segment_properties()
hb.shape(hb.Font(hb.Face(hb.Blob(data.getvalue()))), buf, {'kern': True, 'liga': False})
placed, x = [], 0
for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
    placed.append((order[info.codepoint], x + pos.x_offset, pos.y_offset))
    x += pos.x_advance

bounds = BoundsPen(glyphs)
for name, gx, gy in placed:
    glyphs[name].draw(TransformPen(bounds, (1, 0, 0, 1, gx, gy)))
x_min, y_min, x_max, y_max = bounds.bounds

# Font units, y flipped; the viewBox is the ink box (y from -ascent to +descent).
pen = SVGPathPen(glyphs, ntos=lambda v: ('%.2f' % v).rstrip('0').rstrip('.'))
for name, gx, gy in placed:
    glyphs[name].draw(TransformPen(pen, (1, 0, 0, -1, gx, -gy)))

OUT.write_text(f"""// "{TEXT}" wordmark as a single vector path: Montserrat Bold (SIL Open Font
// License 1.1), default spacing and kerning, in font units (1000/em) with y
// down. The viewBox is the letters' own ink box, so centring the box centres
// the word. Generated by scripts/generate-wordmark-path.py -- do not edit by hand.
export const WORDMARK_VIEWBOX = {{ x: {x_min:g}, y: {-y_max:g}, width: {x_max - x_min:g}, height: {y_max - y_min:g} }}

export const WORDMARK_COLOR = '{COLOR}'

export const WORDMARK_PATH =
  '{pen.getCommands()}'
""")
print(f'wrote {OUT.relative_to(OUT.parents[2])}')
