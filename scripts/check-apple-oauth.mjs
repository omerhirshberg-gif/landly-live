// Read-only: would Sign in with Apple start on DEV (landly-dev) and PROD
// (landly-be752)? For each host that serves Firebase's auth handler, asks
// Firebase for the Apple authorize URL it would send members to (the same
// accounts:createAuthUri call the handler makes), checks the Services ID in
// it, and asks Apple whether it accepts that Services ID and Return URL.
// "Invalid web redirect url" means the host's https://<host>/__/auth/handler
// is missing from the Services ID's Return URLs in the Apple Developer portal.
// Then has Firebase redeem a made-up code with Apple (accounts:signInWithIdp,
// as the handler does after Face ID): Apple refusing the code (invalid_grant)
// shows Firebase sends a client secret; invalid_client, that its Apple
// provider has no key. Apple checks the code before the secret, so this can't
// tell a wrong key from a right one: `npm run check:apple-key` does, with a
// real sign-in. No account is created.
// Then hands Firebase an unsigned Apple identity token addressed to the app's
// bundle ID, as the native sheet's are: Firebase must accept that audience
// (an iOS app with the bundle ID registered in the project), or the app's
// Apple sign-in fails with auth/invalid-credential after Face ID.
// Last, the app's local iOS project (landly-mobile/ios, generated by
// `expo prebuild`) must carry the Sign in with Apple entitlement, or the
// native sheet fails with ERR_REQUEST_UNKNOWN; and must use UIKit's scene
// life cycle, or iOS 27 stops the app the moment it opens.
//
//   npm run check:apple
//
// Uses only each env's public web API key (.env.local, .env.production.local)
// and never prints it. Changes nothing. Exits 1 if any row fails.

import { existsSync, readFileSync } from 'node:fs'
import { randomBytes, randomUUID } from 'node:crypto'
import { join } from 'node:path'
import { parseEnv } from 'node:util'
import { assessRow, classifyNativeAudience, NATIVE_APPLE_AUDIENCE, nativeAppleSignInStatus, nativeSceneLifecycleStatus } from './lib/appleOAuth.mjs'

process.removeAllListeners('warning')
const { PROXIED_AUTH_HOSTS } = await import('../lib/firebase/authDomain.ts')

const root = join(import.meta.dirname, '..')
const ENVS = [
  { label: 'DEV', file: '.env.local' },
  { label: 'PROD', file: '.env.production.local' },
]

function readEnv(file) {
  const path = join(root, file)
  return existsSync(path) ? parseEnv(readFileSync(path, 'utf8')) : null
}

async function authUriFor(apiKey, host) {
  const res = await fetch(`https://identitytoolkit.googleapis.com/v1/accounts:createAuthUri?key=${encodeURIComponent(apiKey)}`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ providerId: 'apple.com', continueUri: `https://${host}/__/auth/handler` }),
  })
  const json = await res.json().catch(() => ({}))
  if (!res.ok || !json.authUri) throw new Error(`createAuthUri ${res.status}: ${json.error?.message ?? 'no authUri'}`)
  return { authUri: json.authUri, sessionId: json.sessionId }
}

// A fresh made-up code each time: Firebase refuses one it has already seen
// (MISSING_OR_INVALID_NONCE) before asking Apple.
async function exchangeMessageFor(apiKey, host, authUri, sessionId) {
  const state = new URL(authUri).searchParams.get('state') ?? ''
  const code = `c${randomBytes(8).toString('hex')}.0.landly-check.invalid`
  const res = await fetch(`https://identitytoolkit.googleapis.com/v1/accounts:signInWithIdp?key=${encodeURIComponent(apiKey)}`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      requestUri: `https://${host}/__/auth/handler`,
      sessionId,
      postBody: `code=${code}&state=${encodeURIComponent(state)}&providerId=apple.com`,
      returnSecureToken: false,
      returnIdpCredential: true,
    }),
  })
  const json = await res.json().catch(() => ({}))
  return json.error?.message ?? (res.ok ? 'accepted a made-up code' : `HTTP ${res.status}`)
}

// Unsigned, so it can never sign anyone in; Firebase checks the audience
// before the signature and nonce.
async function nativeAudienceMessageFor(apiKey) {
  const b64 = (o) => Buffer.from(JSON.stringify(o)).toString('base64url')
  const now = Math.floor(Date.now() / 1000)
  const claims = { iss: 'https://appleid.apple.com', aud: NATIVE_APPLE_AUDIENCE, sub: `landly-check.${randomUUID()}`, iat: now, exp: now + 600, nonce: randomUUID() }
  const idToken = `${b64({ alg: 'RS256', kid: 'landly-check' })}.${b64(claims)}.invalid`
  const res = await fetch(`https://identitytoolkit.googleapis.com/v1/accounts:signInWithIdp?key=${encodeURIComponent(apiKey)}`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      requestUri: 'http://localhost',
      postBody: `id_token=${idToken}&providerId=apple.com&nonce=${randomUUID()}`,
      returnSecureToken: false,
      returnIdpCredential: true,
    }),
  })
  const json = await res.json().catch(() => ({}))
  return json.error?.message ?? (res.ok ? 'accepted an unsigned token' : `HTTP ${res.status}`)
}

const rows = []
for (const { label, file } of ENVS) {
  const env = readEnv(file)
  const projectId = env?.NEXT_PUBLIC_FIREBASE_PROJECT_ID
  const apiKey = env?.NEXT_PUBLIC_FIREBASE_API_KEY
  if (!projectId || !apiKey) {
    rows.push({ label, projectId: projectId ?? '?', host: '-', ok: false, note: `${file} missing or incomplete` })
    continue
  }
  const hosts = [env.NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN || `${projectId}.firebaseapp.com`]
  if (env.NEXT_PUBLIC_FIREBASE_AUTH_PROXY === '1') hosts.push(...PROXIED_AUTH_HOSTS)
  for (const host of hosts) {
    try {
      const { authUri, sessionId } = await authUriFor(apiKey, host)
      const res = await fetch(authUri, { redirect: 'manual' })
      const body = await res.text()
      const exchangeMessage = await exchangeMessageFor(apiKey, host, authUri, sessionId)
      const row = assessRow({ projectId, host, authUri, status: res.status, body, exchangeMessage })
      const notes = []
      if (row.clientId !== row.expectedClientId) notes.push(`client_id ${row.clientId}, expected ${row.expectedClientId}`)
      if (row.exchange === 'unknown') notes.push(`token exchange: ${exchangeMessage.split(',')[0].slice(0, 160)}`)
      if (row.exchange === 'no-key') notes.push("Firebase sends Apple no client secret: enter the Team ID, Key ID and .p8 in this project's Apple provider")
      const note = notes.join('; ')
      rows.push({ label, ...row, note })
    } catch (err) {
      rows.push({ label, projectId, host, ok: false, note: err instanceof Error ? err.message : String(err) })
    }
  }
  try {
    const message = await nativeAudienceMessageFor(apiKey)
    const { status, expectedAudience } = classifyNativeAudience(message)
    const notes = {
      'native-ok': `iOS app ${NATIVE_APPLE_AUDIENCE} accepted`,
      'aud-mismatch': `Firebase expects ${expectedAudience}: register an iOS app with bundle ID ${NATIVE_APPLE_AUDIENCE} in ${projectId}`,
      'unknown': message.split(',')[0].slice(0, 160),
    }
    rows.push({ label, projectId, host: `native ${NATIVE_APPLE_AUDIENCE}`, apple: status, exchange: '-', ok: status === 'native-ok', note: notes[status] })
  } catch (err) {
    rows.push({ label, projectId, host: 'native aud', ok: false, note: err instanceof Error ? err.message : String(err) })
  }
}

const mobile = join(root, 'landly-mobile')
const entitlementsPath = join(mobile, 'ios', 'Landly', 'Landly.entitlements')
const nativeStatus = nativeAppleSignInStatus({
  appJson: JSON.parse(readFileSync(join(mobile, 'app.json'), 'utf8')),
  entitlements: existsSync(entitlementsPath) ? readFileSync(entitlementsPath, 'utf8') : null,
})
const NATIVE_NOTES = {
  'ok': 'Sign in with Apple entitlement present',
  'no-native-project': 'no local ios/ (EAS generates it)',
  'stale-build': 'ios/ lacks the Sign in with Apple entitlement: run `npx expo prebuild --platform ios` in landly-mobile, then rebuild',
  'missing-config': 'app.json lacks ios.usesAppleSignIn or the expo-apple-authentication plugin',
}
rows.push({
  label: 'APP',
  projectId: 'landly-mobile',
  host: 'ios/Landly/Landly.entitlements',
  apple: nativeStatus,
  exchange: '-',
  ok: nativeStatus === 'ok' || nativeStatus === 'no-native-project',
  note: NATIVE_NOTES[nativeStatus],
})

const iosApp = join(mobile, 'ios', 'Landly')
const readIfThere = (path) => (existsSync(path) ? readFileSync(path, 'utf8') : null)
const sceneStatus = nativeSceneLifecycleStatus({
  infoPlist: readIfThere(join(iosApp, 'Info.plist')),
  pbxproj: readIfThere(join(mobile, 'ios', 'Landly.xcodeproj', 'project.pbxproj')),
  appDelegate: readIfThere(join(iosApp, 'AppDelegate.swift')),
  sceneDelegate: readIfThere(join(iosApp, 'SceneDelegate.swift')),
})
const SCENE_NOTES = {
  'ok': 'UIScene life cycle adopted (iOS 27)',
  'no-native-project': 'no local ios/ (EAS generates it)',
  'stale-build': 'ios/ lacks the UIScene life cycle, so iOS 27 stops the app at launch: run `npx expo prebuild --platform ios` in landly-mobile',
}
rows.push({
  label: 'APP',
  projectId: 'landly-mobile',
  host: 'ios/Landly (UIScene)',
  apple: sceneStatus,
  exchange: '-',
  ok: sceneStatus === 'ok' || sceneStatus === 'no-native-project',
  note: SCENE_NOTES[sceneStatus],
})

console.log(`     ${'ENV'.padEnd(4)} ${'PROJECT'.padEnd(13)} ${'HOST'.padEnd(30)} ${'AUTHORIZE'.padEnd(12)} ${'SECRET'.padEnd(8)} SERVICES ID`)
for (const r of rows) {
  const status = r.ok ? 'OK  ' : 'FAIL'
  console.log(
    `${status} ${r.label.padEnd(4)} ${r.projectId.padEnd(13)} ${r.host.padEnd(30)} ${(r.apple ?? '-').padEnd(12)} ${(r.exchange ?? '-').padEnd(8)} ${r.clientId ?? ''} ${r.note ?? ''}`.trimEnd(),
  )
}
const failed = rows.filter((r) => !r.ok).length
console.log(failed ? `\n${failed} of ${rows.length} failed.` : `\nAll ${rows.length} OK: Apple accepts every Services ID and Return URL, Firebase sends it a client secret, and the app's iOS project is set up.`)
// Apple only checks the key itself on a real code.
console.log('Whether that secret is signed with the right key: `npm run check:apple-key` (one real sign-in).')
process.exit(failed ? 1 : 0)
