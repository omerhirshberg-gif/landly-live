// Writes lib/profile/countryNames.ts: the full name of every country
// libphonenumber knows, in each app language. The app can't ask the runtime
// (React Native's Hermes has no Intl.DisplayNames, so it showed ISO codes),
// and the browser's names use short forms ("St. Lucia", "Bosnia &
// Herzegovina", "U.S. Virgin Islands", "о-в Мэн", "R.A.S. chinoise de Hong
// Kong"). So the names are taken once from Node's ICU data, then every short
// form is spelled out below, and the result is checked in.
//
//     node scripts/generate-country-names.mjs
//
// Fails if a name still has a short form after the fixes, so a newer ICU
// that introduces one can't slip through.
