// Short forms that must not survive: dots, ampersands, " - " qualifiers,
// "SAR"-style region tags, Russian "о-в(а)", Spanish "EE. UU.".
const SHORT_FORM = /[.&]|\s-\s|\bSAR\b|САР|\bRAE\b|R\.A\.S|о-ва?\b|EE\.\s?UU/

const codes = getCountries().sort()
const out = {}
for (const lang of LANGS) {
  const names = new Intl.DisplayNames([lang], { type: 'region', fallback: 'none' })
  out[lang] = {}
  for (const code of codes) {
    const name = FIXES[lang][code] ?? names.of(code)
    if (!name || name === code) throw new Error(`${lang}.${code}: no name`)
    if (SHORT_FORM.test(name)) throw new Error(`${lang}.${code}: short form left in "${name}"`)
    out[lang][code] = name
  }
}

const body = LANGS.map(
  (lang) => `  ${lang}: {\n${codes.map((code) => `    ${code}: ${JSON.stringify(out[lang][code])},`).join('\n')}\n  },`
).join('\n')

writeFileSync(
  new URL('../lib/profile/countryNames.ts', import.meta.url),
  `// Generated by scripts/generate-country-names.mjs; edit the fixes there, not this file.
// Every country libphonenumber knows, by ISO code, with its full name in each
// app language (no "St.", "&", "SAR", "U.S.", "о-в"…), so web and the app
// show the same names whatever the runtime's Intl support.
import type { Lang } from '@/lib/i18n/translations'

export const COUNTRY_NAMES: Record<Lang, Readonly<Record<string, string>>> = {
${body}
}
`
)
